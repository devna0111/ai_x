-- 0 초기화
DROP TABLE MEMBER;
DROP TABLE MEMBER_LEVEL;
-- 1 생성
CREATE TABLE MEMBER_LEVEL(
    LEVELNO NUMBER(1) PRIMARY KEY,
    LEVELNAME VARCHAR2(50) NOT NULL
);

CREATE SEQUENCE MEMBER_SEQ
    MAXVALUE 99999
    NOCACHE NOCYCLE;
    
CREATE TABLE MEMBER(
    MNO NUMBER(5) PRIMARY KEY,
    MNAME VARCHAR2(50) NOT NULL,
    MPW VARCHAR2(8) NOT NULL,
    MEMAIL VARCHAR2(250) UNIQUE,
    MPOINT NUMBER(9) CHECK(MPOINT>=0),
    MRDATE DATE DEFAULT SYSDATE,
    LEVELNO NUMBER(1) REFERENCES MEMBER_LEVEL(LEVELNO)
);
